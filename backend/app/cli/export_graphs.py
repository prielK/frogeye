"""Write the Mermaid diagrams of the agent graphs (daily intelligence + newsroom).

Usage: python -m app.cli.export_graphs [--out PATH]   (default: print to stdout)
`make graphs` prints them; the README embeds the result.
"""

import argparse
import sys
from pathlib import Path

from app.agents.graphs.daily_intel import build_daily_graph
from app.agents.graphs.newsroom import newsroom_graph

HEADER = """# FrogEye agent graphs

Generated by `python -m app.cli.export_graphs` (`make graphs`) from the compiled LangGraph
graphs; do not edit by hand.

## Daily Intelligence (`app/agents/graphs/daily_intel.py`)

One checkpointed run a day (Celery beat 06:00 Asia/Jerusalem, or `POST /api/v1/runs`).
Without an OpenAI key the run goes straight from `ingest` to `publish` (ingestion only).
Triage and analysis fan out inside their nodes (semaphores of 8 and 4); a budget stop
skips the remaining LLM work and files the briefing as `skipped_budget`.

`analyze` is the short first look at a story (stage A). `deep_analyze` runs after `score`,
so importance is final, and writes the full cited, fact-checked analysis (stage B) of the
most important signals that have none yet (at most `deep_analysis_cap`, 4 in flight), before
the newsroom reads them. A resumed run continues it: current analyses are never redone.
`python -m app.cli.analyze_signals` backfills the same analyses for existing signals.

`tag_postings` runs right after `index_new`: the fast model labels open job postings that
have no tags yet with product-area (capability) slugs, newest first, at most
`posting_tag_cap` per run. It does not touch the news pipeline; a failure leaves postings
untagged for the next run. `python -m app.cli.tag_postings` backfills the same tags.

`judge_pages` runs right after `tag_postings`: the fast model judges each page-watch diff (a
competitor pricing, about or careers page that changed since the last daily fetch) that is
big enough to matter. A meaningful pricing, packaging or product change becomes a document,
embedded in the node so `triage` reads it in the same run; the rest are only recorded. A
failure or a budget stop leaves the diffs unjudged for the next run.

`extract_facts` runs right after `deep_analyze`: the smart model reads relevant documents and
about/careers page snapshots that pass a keyword screen (a changed page by its new lines
only) for company facts such as funding rounds, headcount, revenue, customers, market share,
acquisitions, leadership changes, partners and offices, at most `fact_extract_cap` sources
per run, newest first. A fact is stored only when its verbatim quote matches the source and
its figures and date come from that quote (or the source's date); conflicting sources stay
separate rows, never averaged. Each source is read once, and JFrog itself never gets facts.
It starts nothing once the day's remaining budget is the newsroom's reserve, and a failure or
a budget stop leaves the unread sources for the next run. `python -m app.cli.extract_facts`
backfills the same facts.
"""

NEWSROOM = """
## Newsroom (`app/agents/graphs/newsroom/`)

The `newsroom` node's subgraph: the editor plans the master briefing (headline, lead,
takeaway titles, themes and order) and the fact-checker checks that text. Each role
edition's lead stories are then chosen in code: the top three of the master's stories by
role score (Exec's weighted by the analysis's risk level) that have an action for that
role, at most two about one company, and at least one the master does not lead with when
another story qualifies. One role adapter per edition titles those stories, writes its
own headline and lead (checked again) and picks its other stories, then assembly. Card
text is copied from each signal's verified analysis (an edition's card says why the story
matters from the role's own section of it), or from its stage-A text when it has none,
never written here. It has no checkpointer of its own, so a resumed daily run re-runs it
whole.
"""


def render() -> str:
    # Drawing compiles the graphs but runs no node, so no dependencies are needed.
    daily = build_daily_graph(None).get_graph().draw_mermaid()
    newsroom = newsroom_graph().get_graph().draw_mermaid()
    return (
        f"{HEADER}\n```mermaid\n{daily.strip()}\n```\n"
        f"{NEWSROOM}\n```mermaid\n{newsroom.strip()}\n```\n"
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="python -m app.cli.export_graphs")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)
    text = render()
    if args.out is None:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stdout.write(text)
    else:
        args.out.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
